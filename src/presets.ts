// Built-in presets, in the same JSON form that "Save preset" writes.
// `params` holds only what differs from the init patch, in real units.
// `demo` picks the phrase the demo player uses for this sound.

import type { ModJSON, PatchJSON } from './patch-json.ts';

export type Category = 'basic' | 'bass' | 'lead' | 'pad' | 'chord' | 'pluck' | 'keys' | 'fx';

export interface Preset extends PatchJSON {
  name: string;
  /** Japanese name. */
  ja?: string;
  cat: Category;
  /** Phrase the demo player uses for this sound. */
  demo: string;
  /** A tip shown when the preset is loaded: [Japanese, English]. */
  note?: [string, string];
  /** Extra words for steps of its lesson, by the step's node: [Japanese, English]. */
  lesson?: Record<string, [string, string]>;
}

const mod = (source: string, target: string, amount: number, bipolar = false): ModJSON => ({ source, target, amount, ...(bipolar ? { bipolar } : {}) });

